DROP TABLE IF EXISTS user_skills;
DROP TABLE IF EXISTS users;
DROP TABLE IF EXISTS careers;
DROP TABLE IF EXISTS skills;
DROP TABLE IF EXISTS roles;

CREATE TABLE roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    description VARCHAR(255)
);

CREATE TABLE careers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    description CLOB,
    category VARCHAR(100),
    averageSalary DOUBLE,
    demandLevel VARCHAR(50)
);

CREATE TABLE skills (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description CLOB,
    category VARCHAR(100)
);

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname VARCHAR(100) NOT NULL,
    lastname VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    experienceLevel VARCHAR(50),
    roleId INTEGER,
    createdAt TIMESTAMP NOT NULL,
    updatedAt TIMESTAMP NOT NULL,
    CONSTRAINT fk_users_role FOREIGN KEY (roleId) REFERENCES roles(id)
);

CREATE TABLE user_skills (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userId INTEGER NOT NULL,
    skillId INTEGER NOT NULL,
    proficiencyLevel VARCHAR(50),
    createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_skills_user FOREIGN KEY (userId) REFERENCES users(id),
    CONSTRAINT fk_user_skills_skill FOREIGN KEY (skillId) REFERENCES skills(id),
    CONSTRAINT uk_user_skill UNIQUE (userId, skillId)
);
